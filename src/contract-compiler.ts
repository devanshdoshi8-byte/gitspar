import { writeFileSync } from 'node:fs';
import { resolve, relative, dirname, basename } from 'node:path';
import { ExecutedProbe } from './oracle-probe.js';

export type ContractVerdict = 'INTENDED' | 'DEFECT';

export interface HumanVerdictDecision {
  probe: ExecutedProbe;
  verdict: ContractVerdict;
  expectedOutput?: unknown;
  intentNote?: string;
}

export interface ContractCompilationOptions {
  functionName: string;
  sourceFilePath: string;
  decisions: HumanVerdictDecision[];
  generatedBy?: string;
  timestamp?: string;
}

export interface CompiledContractResult {
  testFilePath: string;
  testFileContent: string;
  prMarkdownTable: string;
  summary: {
    totalProbes: number;
    intendedCount: number;
    defectCount: number;
  };
}

/**
 * Generates the content of the Vitest regression test suite (<filename>.spar.test.ts).
 */
export function generateVitestRegressionSuite(options: ContractCompilationOptions): string {
  const { functionName, sourceFilePath, decisions, timestamp } = options;
  const time = timestamp || new Date().toISOString();

  // Compute import path relative to the test file
  // Test file will typically be created adjacent to source file: <dir>/<name>.spar.test.ts
  const baseName = basename(sourceFilePath).replace(/\.tsx?$/, '');
  const importRelPath = `./${baseName}.js`;

  const lines: string[] = [
    `// ====================================================================`,
    `// Generated by GitSpar (v0.3.0) — Executable Intent Contract`,
    `// Function:     ${functionName}`,
    `// Source File:  ${sourceFilePath}`,
    `// Verified At:  ${time}`,
    `// ====================================================================`,
    `import { describe, it, expect } from 'vitest';`,
    `import { ${functionName} } from '${importRelPath}';`,
    ``,
    `describe('Intent Contract Regression Suite: ${functionName}()', () => {`,
  ];

  decisions.forEach((decision, index) => {
    const { probe, verdict, expectedOutput, intentNote } = decision;
    const inputFormatted = JSON.stringify(probe.inputArgs);
    const probeIndex = index + 1;
    const note = intentNote || probe.description;

    if (verdict === 'INTENDED') {
      lines.push(`  // Edge Case ${probeIndex} [${probe.categoryLabel}]: Owner confirmed intended business rule`);
      lines.push(`  // Input: ${inputFormatted} -> Output: ${probe.actualOutputJson}`);
      lines.push(`  it('contract #${probeIndex} [INTENDED]: ${note.replace(/'/g, "\\'")}', () => {`);

      if (probe.isFloatOutput && typeof probe.actualOutput === 'number') {
        lines.push(`    const result = ${functionName}(...(${inputFormatted} as any));`);
        lines.push(`    expect(result).toBeCloseTo(${probe.actualOutput}, 4);`);
      } else {
        lines.push(`    const result = ${functionName}(...(${inputFormatted} as any));`);
        lines.push(`    expect(result).toEqual(${JSON.stringify(probe.actualOutput)});`);
      }
      lines.push(`  });`);
      lines.push(``);
    } else {
      // DEFECT
      const targetExpectation = expectedOutput !== undefined ? expectedOutput : 'CORRECTED_EXPECTATION';
      lines.push(`  // Edge Case ${probeIndex} [${probe.categoryLabel}]: Owner flagged AI DEFECT`);
      lines.push(`  // Observed: ${probe.actualOutputJson} | Expected: ${JSON.stringify(targetExpectation)}`);
      lines.push(`  it.fails('contract #${probeIndex} [DEFECT]: ${note.replace(/'/g, "\\'")} (TODO: fix boundary)', () => {`);
      lines.push(`    // Current implementation returned: ${probe.actualOutputJson}`);
      lines.push(`    // Required product rule:   ${JSON.stringify(targetExpectation)}`);
      lines.push(`    const result = ${functionName}(...(${inputFormatted} as any));`);
      lines.push(`    expect(result).toEqual(${JSON.stringify(targetExpectation)});`);
      lines.push(`  });`);
      lines.push(``);
    }
  });

  lines.push(`});`);
  lines.push(``);

  return lines.join('\n');
}

/**
 * Generates a clean, compact Markdown PR Contract table ready to paste into GitHub PR descriptions.
 */
export function generatePrContractMarkdown(options: ContractCompilationOptions): string {
  const { functionName, decisions, timestamp } = options;
  const time = timestamp || new Date().toISOString();

  const lines: string[] = [
    `### 🛡️ GitSpar Verified Intent Contract (\`${functionName}\`)`,
    ``,
    `> **Contract Attestation:** Human code owner probed ${decisions.length} edge cases against this AI diff. Behaviors verified and compiled into permanent Vitest regression specs.`,
    ``,
    `| Edge Case Category | Input Arguments | Observed Output | Owner Verdict | Intent Specification |`,
    `| :--- | :--- | :--- | :---: | :--- |`,
  ];

  for (const decision of decisions) {
    const { probe, verdict, expectedOutput, intentNote } = decision;
    const inputCell = `\`${JSON.stringify(probe.inputArgs)}\``;
    const outputCell = `\`${probe.actualOutputJson}\``;
    const verdictBadge = verdict === 'INTENDED' ? '✅ **INTENDED**' : '⚠️ **DEFECT**';
    const noteCell =
      verdict === 'DEFECT'
        ? `*Defect caught.* Expected \`${JSON.stringify(expectedOutput)}\` (${intentNote || 'fix required'})`
        : intentNote || probe.description;

    lines.push(
      `| **${probe.categoryLabel}** | ${inputCell} | ${outputCell} | ${verdictBadge} | ${noteCell} |`
    );
  }

  lines.push(``);
  lines.push(`*Generated by GitSpar JiT-Oracle at ${time} — Locked in \`<filename>.spar.test.ts\`*`);

  return lines.join('\n');
}

/**
 * Compiles decisions into Vitest test suite and Markdown table, and writes test file to disk.
 */
export function compileAndSaveContract(
  options: ContractCompilationOptions,
  cwd: string = process.cwd()
): CompiledContractResult {
  const { sourceFilePath, decisions } = options;
  const absSource = resolve(cwd, sourceFilePath);
  const dir = dirname(absSource);
  const baseName = basename(absSource).replace(/\.tsx?$/, '');
  const testFilePath = resolve(dir, `${baseName}.spar.test.ts`);

  const testFileContent = generateVitestRegressionSuite(options);
  const prMarkdownTable = generatePrContractMarkdown(options);

  // Write regression test file to disk
  writeFileSync(testFilePath, testFileContent, 'utf-8');

  const intendedCount = decisions.filter((d) => d.verdict === 'INTENDED').length;
  const defectCount = decisions.filter((d) => d.verdict === 'DEFECT').length;

  return {
    testFilePath,
    testFileContent,
    prMarkdownTable,
    summary: {
      totalProbes: decisions.length,
      intendedCount,
      defectCount,
    },
  };
}
