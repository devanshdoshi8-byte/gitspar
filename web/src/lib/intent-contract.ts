export type ProbeCategory =
  | 'boundary_threshold'
  | 'zero_empty_nullish'
  | 'floating_point_precision'
  | 'concurrency_async';

export interface ExecutedProbe {
  probeId: string;
  category: ProbeCategory;
  categoryLabel: string;
  description: string;
  inputArgs: unknown[];
  inputArgsJson: string;
  actualOutput: unknown;
  actualOutputJson: string;
  isFloatOutput: boolean;
  executionMs: number;
}

export type ContractVerdict = 'INTENDED' | 'DEFECT';

export interface HumanVerdictDecision {
  probe: ExecutedProbe;
  verdict: ContractVerdict;
  expectedOutput?: unknown;
  intentNote?: string;
}

export interface ContractCompilationOptions {
  functionName: string;
  sourceFilePath: string;
  decisions: HumanVerdictDecision[];
  timestamp?: string;
}

/**
 * Client-side probe synthesizer for the interactive demo.
 * Evaluates pure functions in the browser sandbox.
 */
export function synthesizeClientProbes(
  code: string,
  functionName: string = 'calculateTierDiscount'
): ExecutedProbe[] {
  // Try evaluating the function in an isolated browser Function context
  let fnRunner: ((...args: unknown[]) => unknown) | null = null;
  try {
    const cleanCode = code.replace(/export\s+(default\s+)?/g, '');
    const wrappedCode = `${cleanCode}\nreturn typeof ${functionName} === 'function' ? ${functionName} : null;`;
    const fnBuilder = new Function(wrappedCode);
    fnRunner = fnBuilder();
  } catch {
    // Handled via fallback outputs
  }

  // Pre-configured high-signal edge-case probes
  const probeConfigs: {
    id: string;
    category: ProbeCategory;
    categoryLabel: string;
    description: string;
    args: unknown[];
    fallbackOutput: unknown;
  }[] = [
    {
      id: 'PROBE-1',
      category: 'boundary_threshold',
      categoryLabel: 'Exact Boundary Threshold',
      description: 'Tests exact threshold boundary (orderTotal = 100) where volume discount kicks in.',
      args: [100, false],
      fallbackOutput: 90,
    },
    {
      id: 'PROBE-2',
      category: 'zero_empty_nullish',
      categoryLabel: 'Zero / Empty Baseline Guard',
      description: 'Tests lower boundary minimum (orderTotal = 0) to ensure negative/zero guard passes.',
      args: [0, false],
      fallbackOutput: 0,
    },
    {
      id: 'PROBE-3',
      category: 'floating_point_precision',
      categoryLabel: 'Floating-Point / Penny Rounding',
      description: 'Fractional rate calculation on 101 * 0.8 producing IEEE-754 precision artifact (80.80000000000001).',
      args: [101, true],
      fallbackOutput: 80.8,
    },
  ];

  return probeConfigs.map((cfg) => {
    let actualOutput = cfg.fallbackOutput;
    let executionMs = 0.5;

    if (fnRunner) {
      const t0 = performance.now();
      try {
        actualOutput = fnRunner(...cfg.args);
      } catch (err) {
        console.error('Execution error in probe:', err);
      }
      executionMs = Math.round((performance.now() - t0) * 100) / 100;
    }

    const isFloat = typeof actualOutput === 'number' && !Number.isInteger(actualOutput);
    const actualOutputJson =
      typeof actualOutput === 'number'
        ? Number(actualOutput.toFixed(4)).toString()
        : JSON.stringify(actualOutput);

    return {
      probeId: cfg.id,
      category: cfg.category,
      categoryLabel: cfg.categoryLabel,
      description: cfg.description,
      inputArgs: cfg.args,
      inputArgsJson: JSON.stringify(cfg.args),
      actualOutput,
      actualOutputJson,
      isFloatOutput: isFloat,
      executionMs,
    };
  });
}

/**
 * Generates the clean Vitest regression test file.
 */
export function generateVitestRegressionSuite(options: ContractCompilationOptions): string {
  const { functionName, sourceFilePath, decisions, timestamp } = options;
  const time = timestamp || new Date().toISOString();

  const lines: string[] = [
    `// ====================================================================`,
    `// Generated by GitSpar (v0.3.0) — Executable Intent Contract`,
    `// Function:     ${functionName}`,
    `// Source File:  ${sourceFilePath}`,
    `// Verified At:  ${time}`,
    `// ====================================================================`,
    `import { describe, it, expect } from 'vitest';`,
    `import { ${functionName} } from './${functionName}.js';`,
    ``,
    `describe('Intent Contract: ${functionName}()', () => {`,
  ];

  decisions.forEach((decision, index) => {
    const { probe, verdict, expectedOutput, intentNote } = decision;
    const inputFormatted = JSON.stringify(probe.inputArgs);
    const probeIndex = index + 1;
    const note = intentNote || probe.description;

    if (verdict === 'INTENDED') {
      lines.push(`  // Edge Case #${probeIndex} [${probe.categoryLabel}]: Confirmed by code owner`);
      lines.push(`  it('contract #${probeIndex} [INTENDED]: ${note.replace(/'/g, "\\'")}', () => {`);
      if (probe.isFloatOutput && typeof probe.actualOutput === 'number') {
        lines.push(`    const result = ${functionName}(...(${inputFormatted} as any));`);
        lines.push(`    expect(result).toBeCloseTo(${Number(probe.actualOutput.toFixed(4))}, 4);`);
      } else {
        lines.push(`    const result = ${functionName}(...(${inputFormatted} as any));`);
        lines.push(`    expect(result).toEqual(${JSON.stringify(probe.actualOutput)});`);
      }
      lines.push(`  });`);
      lines.push(``);
    } else {
      const targetExpectation = expectedOutput !== undefined ? expectedOutput : 'CORRECTED_VALUE';
      lines.push(`  // Edge Case #${probeIndex} [${probe.categoryLabel}]: Flagged as AI defect`);
      lines.push(`  it.fails('contract #${probeIndex} [DEFECT]: ${note.replace(/'/g, "\\'")} (TODO: fix boundary)', () => {`);
      lines.push(`    // Current implementation returned: ${probe.actualOutputJson}`);
      lines.push(`    // Expected intended product rule: ${JSON.stringify(targetExpectation)}`);
      lines.push(`    const result = ${functionName}(...(${inputFormatted} as any));`);
      lines.push(`    expect(result).toEqual(${JSON.stringify(targetExpectation)});`);
      lines.push(`  });`);
      lines.push(``);
    }
  });

  lines.push(`});`);
  return lines.join('\n');
}

/**
 * Generates the GitHub PR description markdown table.
 */
export function generatePrContractMarkdown(options: ContractCompilationOptions): string {
  const { functionName, decisions, timestamp } = options;
  const time = timestamp || new Date().toISOString();

  const lines: string[] = [
    `### 🛡️ GitSpar Verified Intent Contract (\`${functionName}\`)`,
    ``,
    `> **Contract Attestation:** Human code owner probed ${decisions.length} edge cases against this AI diff. Behaviors verified and compiled into permanent Vitest regression specs.`,
    ``,
    `| Edge Case Category | Input Arguments | Observed Output | Owner Verdict | Intent Specification |`,
    `| :--- | :--- | :--- | :---: | :--- |`,
  ];

  for (const decision of decisions) {
    const { probe, verdict, expectedOutput, intentNote } = decision;
    const inputCell = `\`${JSON.stringify(probe.inputArgs)}\``;
    const outputCell = `\`${probe.actualOutputJson}\``;
    const verdictBadge = verdict === 'INTENDED' ? '✅ **INTENDED**' : '⚠️ **DEFECT**';
    const noteCell =
      verdict === 'DEFECT'
        ? `*Defect caught.* Expected \`${JSON.stringify(expectedOutput)}\` (${intentNote || 'fix required'})`
        : intentNote || probe.description;

    lines.push(
      `| **${probe.categoryLabel}** | ${inputCell} | ${outputCell} | ${verdictBadge} | ${noteCell} |`
    );
  }

  lines.push(``);
  lines.push(`*Generated by GitSpar JiT-Oracle at ${time} — Locked in \`<filename>.spar.test.ts\`*`);

  return lines.join('\n');
}
